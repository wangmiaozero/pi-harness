export const messages = {
  'zh-CN': zhCN,
  'en-US': enUS
} as const

export type AppLocale = keyof typeof messages

export const i18n = createI18n({
  legacy: false,
  locale: 'zh-CN',
  fallbackLocale: 'zh-CN',
  messages
})

/** Resolve settings language → active locale. Product default is zh-CN. */
export function resolveLocale(language: 'auto' | 'zh-CN' | 'en-US'): AppLocale {
  if (language === 'zh-CN') return 'zh-CN'
  if (language === 'en-US') return 'en-US'
  const nav = typeof navigator !== 'undefined' ? navigator.language : 'zh-CN'
  if (nav.toLowerCase().startsWith('en')) return 'en-US'
  return 'zh-CN'
}
