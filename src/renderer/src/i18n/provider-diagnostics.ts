import {
  connectionHints,
  type ConnectionTestStatus
} from '@shared/providers/connection-diagnostics'

type Labels = readonly [
  provider: string,
  proxy: string,
  transport: string,
  route: string,
  code: string,
  details: string,
  copy: string,
  autoHint: string,
  notStarted: string,
  models: string,
  noModels: string,
  streamingOnly: string,
  disabled: string,
  unsupportedProtocol: string,
  invalidEndpoint: string,
  recursiveUpstream: string,
  fallbackOnly: string,
  unverified: string
]

function messages(
  [
    provider,
    proxy,
    transport,
    route,
    code,
    details,
    copy,
    autoHint,
    notStarted,
    models,
    noModels,
    streamingOnly,
    disabled,
    unsupported_protocol,
    invalid_endpoint,
    recursive_upstream,
    fallback_only,
    unverified
  ]: Labels,
  [auto, system, direct, custom]: readonly [string, string, string, string],
  [environment, login_shell]: readonly [string, string],
  [upstreamCode, upstreamParameter]: readonly [string, string],
  hints: Record<ConnectionTestStatus, string>
) {
  return {
    provider,
    proxy,
    transport,
    route,
    code,
    details,
    copy,
    autoHint,
    notStarted,
    models,
    noModels,
    streamingOnly,
    disabled,
    unsupported_protocol,
    invalid_endpoint,
    recursive_upstream,
    fallback_only,
    unverified,
    modes: { auto, system, direct, custom },
    sources: { environment, system, login_shell },
    upstreamCode,
    upstreamParameter,
    hints
  }
}

